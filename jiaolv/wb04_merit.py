# ---------------------------------------------------------------- 本讲画法

def big_phone(x, y, w=420, h=620) -> skia.Path:
    """大手机屏。"""
    return join(rect(x, y, w, h, 40), P((x - w / 2, y - h / 2 + 80), (x + w / 2, y - h / 2 + 80)),
                P((x - 40, y + h / 2 - 34), (x + 40, y + h / 2 - 34)))


def thought(x, y, w, h) -> skia.Path:
    """想法泡泡：圆角框 + 往左下的两个小圆。"""
    return join(rect(x, y, w, h, 60), circle(x - w * 0.32, y + h / 2 + 40, 20), circle(x - w * 0.42, y + h / 2 + 90, 13))


def ring(x, y, rx, ry) -> skia.Path:
    p = skia.Path()
    p.addOval(skia.Rect.MakeXYWH(x - rx, y - ry, 2 * rx, 2 * ry))
    return p


def ladder(x, bottom, h=600, w=160, rungs=6) -> skia.Path:
    """梯子：(x, bottom) 为底边中点。"""
    parts = [P((x - w / 2, bottom), (x - w / 2, bottom - h)), P((x + w / 2, bottom), (x + w / 2, bottom - h))]
    for i in range(rungs):
        yy = bottom - 50 - i * (h - 80) / (rungs - 1)
        parts.append(P((x - w / 2, yy), (x + w / 2, yy)))
    return join(*parts)


def dice(x, y, s=180) -> skia.Path:
    """骰子（五点面）。"""
    p = rect(x, y, s, s, 26)
    for dx, dy in ((-1, -1), (1, -1), (0, 0), (-1, 1), (1, 1)):
        p.addCircle(x + dx * s * 0.27, y + dy * s * 0.27, s * 0.07)
    return p


def house(x, y, w=380, h=280) -> skia.Path:
    """房子：(x, y) 为底边中点。"""
    return join(P((x - w / 2, y), (x - w / 2, y - h), (x + w / 2, y - h), (x + w / 2, y)),
                P((x - w / 2 - 40, y - h), (x, y - h - 190), (x + w / 2 + 40, y - h)),
                rect(x - w / 4, y - h * 0.6, 80, 80, 6), P((x + 40, y), (x + 40, y - 130), (x + 120, y - 130), (x + 120, y)))


def weight(x, y, w=380, h=170) -> skia.Path:
    """压在头上的大秤砣（梯形 + 提环）。"""
    return join(P((x - w / 2 + 40, y - h / 2), (x + w / 2 - 40, y - h / 2), (x + w / 2, y + h / 2), (x - w / 2, y + h / 2),
                  close=True), circle(x, y - h / 2 - 30, 30))


def strike(x, y, w) -> skia.Path:
    return P((x - w / 2, y), (x + w / 2, y))


