def T(s, x, y, size=72, color=BLACK, k0=0.0, k1=None, sfx=None, j=None):
    """在当前镜头写字：写字时长按字数估计（每字约 0.18 拍，至少 0.5 拍）。"""
    jj = len(b.shots) - 1 if j is None else j
    if k1 is None:
        k1 = k0 + max(0.5, 0.18 * len(s))
        if k0 < 2.6:
            k1 = min(k1, 3.1)          # 联系表取景（约第 3.25 拍）前写完
    b.text(jj, k0, k1, s, x, y, size, color, sfx=sfx)


def L(path, k0, k1, color=BLACK, width=10, sfx=None):
    b.path(len(b.shots) - 1, k0, k1, path, color, width, sfx=sfx)


def J():
    return len(b.shots) - 1


def H(k, sfx, gain=0.8, note=""):
    b.hit(J(), k, sfx, gain, note)


# ---------------------------------------------------------------- 本讲小画法

def phone(x, y, w=200, h=340):
    return join(rect(x, y, w, h, 30), P((x - 30, y + h / 2 - 30), (x + 30, y + h / 2 - 30)))


def contacts(x, y, n=4, gap=80, w=150):
    """手机里的好友列表：头像圈 + 名字横线。(x, y) 为第一行中点。"""
    parts = []
    for i in range(n):
        yy = y + i * gap
        parts.append(circle(x - w / 2, yy, 24))
        parts.append(P((x - w / 2 + 45, yy), (x + w / 2, yy)))
    return join(*parts)


def calendar(x, y, w=300, h=280):
    top = y - h / 2 + 70
    parts = [rect(x, y, w, h, 20), P((x - w / 2, top), (x + w / 2, top)),
             P((x - w / 4, y - h / 2 - 25), (x - w / 4, y - h / 2 + 25)),
             P((x + w / 4, y - h / 2 - 25), (x + w / 4, y - h / 2 + 25))]
    for r in range(2):
        for cc in range(3):
            parts.append(circle(x - w / 3 + cc * w / 3, top + (h - 70) * (0.3 + 0.4 * r), 10))
    return join(*parts)


def cake(x, y, w=260, h=130):
    """生日蛋糕：(x, y) 为蛋糕中心，上面三根蜡烛。"""
    parts = [rect(x, y, w, h, 16), P((x - w / 2, y - 10), (x + w / 2, y - 10)),
             P((x - w / 2 - 30, y + h / 2), (x + w / 2 + 30, y + h / 2))]
    for i in (-1, 0, 1):
        cx = x + i * 70
        parts.append(P((cx, y - h / 2), (cx, y - h / 2 - 60)))
        parts.append(P((cx, y - h / 2 - 72), (cx - 10, y - h / 2 - 90), (cx, y - h / 2 - 108), (cx + 10, y - h / 2 - 90),
                       close=True))
    return join(*parts)


