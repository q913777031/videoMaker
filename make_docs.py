def main():
    out = ["# 5 条无声知识短视频：字幕全文、发布素材与事实核查", "",
           "全部为 1080×1920、30fps、无音轨的 MP4。屏幕字幕即口播文案，后续如需配音可直接照读。",
           "画面为程序绘制的复古插画动画；所有数字、曲线与人物均为教学示意，已在画面左上角标注。", ""]
    for k, mod in MODS.items():
        ep = importlib.import_module("explainer." + mod).build()
        m = META[k]
        out += [f"## 第 {k} 期 · {m['title']}", "",
                f"- 文件：`videos/{ep.name}.mp4`", f"- 时长：约 {ep.total:.0f} 秒；字幕 {ep.chars()} 字；{len(ep.shots)} 个镜头",
                f"- 开场大标题：{m['hook']}", "", "### 字幕（口播）全文", ""]
        for s in ep.shots:
            for cue in s.cues:
                txt = cue if isinstance(cue, str) else cue[0]
                out.append(f"- {plain(txt)}")
        out += ["", "### 发布素材", "", "封面问题标题：", ""]
        out += [f"{i + 1}. {t}" for i, t in enumerate(m["covers"])]
        out += ["", f"发布文案：{m['post']}", "", "话题标签：" + " ".join(m["tags"]), "", "### 事实核查", "",
                "| 类别 | 内容 |", "|---|---|"]
        out += [f"| {a} | {b} |" for a, b in m["facts"]]
        out += [""]
    Path("videos").mkdir(exist_ok=True)
    Path("videos/脚本与核查.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("已生成 videos/脚本与核查.md")


if __name__ == "__main__":
    main()
